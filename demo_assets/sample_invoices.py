import os
from PIL import Image, ImageDraw, ImageFont
import io

def generate_invoice_image(
    invoice_number="KZ-7841/Т",
    supplier="ТОО 'Прима Дистрибьюшн Тараз'",
    date="2026-10-12",
    items=None
) -> bytes:
    """Генерация реалистичного изображения казахстанской товарной накладной"""
    if items is None:
        items = [
            ("Молоко 'Родина' 3.2% 1л", "25 шт", "440.00", "11 000.00"),
            ("Мука пшеничная 'Цесна' 1-сорт 2кг", "10 шт", "760.00", "7 600.00"),
            ("Чай черный 'Пиала Gold' 250г", "15 шт", "950.00", "14 250.00"),
            ("Макароны 'Султан' Спагетти 400г", "30 шт", "320.00", "9 600.00"),
        ]
        
    width, height = 750, 600
    img = Image.new("RGB", (width, height), color=(250, 250, 248))
    draw = ImageDraw.Draw(img)
    
    # Рамка документа
    draw.rectangle([(20, 20), (width - 20, height - 20)], outline=(180, 180, 180), width=2)
    
    # Шапка
    draw.text((40, 40), "ТАУАРЛЫҚ ЖҮКҚҰЖАТ / ТОВАРНАЯ НАКЛАДНАЯ", fill=(20, 30, 60))
    draw.text((40, 65), f"Номер: {invoice_number}       Дата: {date}", fill=(60, 60, 60))
    draw.text((40, 90), f"Поставщик / Жөнелтуші: {supplier}", fill=(20, 20, 20))
    draw.text((40, 110), "Пункт разгрузки: г. Тараз, ул. Толе би, 45, Магазин 'Береке'", fill=(80, 80, 80))
    
    # Разделитель
    draw.line([(40, 140), (width - 40, 140)], fill=(120, 120, 120), width=2)
    
    # Заголовки таблицы
    draw.text((45, 155), "№", fill=(40, 40, 40))
    draw.text((80, 155), "Наименование товара / Тауар атауы", fill=(40, 40, 40))
    draw.text((430, 155), "Кол-во", fill=(40, 40, 40))
    draw.text((520, 155), "Цена закупа (₸)", fill=(40, 40, 40))
    draw.text((640, 155), "Сумма (₸)", fill=(40, 40, 40))
    
    draw.line([(40, 180), (width - 40, 180)], fill=(160, 160, 160), width=1)
    
    y = 195
    total_sum = 0
    for idx, (name, qty, price, total) in enumerate(items, 1):
        draw.text((45, y), str(idx), fill=(60, 60, 60))
        draw.text((80, y), name, fill=(30, 30, 30))
        draw.text((430, y), qty, fill=(50, 50, 50))
        draw.text((520, y), price, fill=(20, 20, 20))
        draw.text((640, y), total, fill=(10, 10, 10))
        y += 35
        
    draw.line([(40, y + 10), (width - 40, y + 10)], fill=(120, 120, 120), width=2)
    
    # Итого
    draw.text((430, y + 25), "ИТОГО К ОПЛАТЕ:", fill=(20, 20, 20))
    draw.text((620, y + 25), "42 450.00 ₸", fill=(180, 20, 20))
    
    # Подписи
    draw.text((50, height - 70), "Отпустил экспедитор: ____________ (қолы)", fill=(100, 100, 100))
    draw.text((400, height - 70), "Принял товаровед: ____________ (қолы / мөр)", fill=(100, 100, 100))
    
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return buf.getvalue()

